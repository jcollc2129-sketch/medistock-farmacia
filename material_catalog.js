async function importarMaterialNoCargoFaltante() {
  const mats = await getMateriales();
  const key = (m) => (m.nombre || "").toLowerCase().trim();
  const existing = new Set(mats.map(key));
  let added = 0;
  for (const d of DOTACION_MATERIAL_NO_CARGO) {
    const k = (d.nombre || "").toLowerCase().trim();
    if (existing.has(k)) continue;
    await addMaterial({
      nombre: d.nombre,
      categoria: d.categoria || "otros",
      referencia: d.presentacion || null,
      barcode: null,
      stockMinimo: d.stockMinimo || 0,
      ubicacion: "",
      notas: "Material sanitario de no cargo",
      tipoStock: "no_cargo",
      foto: null,
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString()
    });
    existing.add(k);
    added++;
  }
  return added;
}

async function seedMaterialNoCargoIfEmpty() {
  const n = await importarMaterialNoCargoFaltante();
  return { seeded: n > 0, count: n };
}
